CREATE TABLE IF NOT EXISTS apartment_objects (
  key TEXT PRIMARY KEY,
  etag TEXT NOT NULL,
  metadata TEXT NOT NULL CHECK(json_valid(metadata)),
  part_count INTEGER NOT NULL CHECK(part_count > 0)
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS apartment_object_parts (
  key TEXT NOT NULL,
  etag TEXT NOT NULL,
  part INTEGER NOT NULL CHECK(part >= 0),
  body TEXT NOT NULL,
  PRIMARY KEY (key, part)
) WITHOUT ROWID;

-- Listing snapshots: each source's latest check (server/d1-bucket.ts). One row per listing, indexed by
-- region and rent so a search reads only what it can match, and one row per unit's price history.
CREATE TABLE IF NOT EXISTS listing_snapshots (
  key TEXT PRIMARY KEY,
  etag TEXT NOT NULL,
  summary TEXT NOT NULL CHECK(json_valid(summary))
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS listings (
  snapshot TEXT NOT NULL,
  position INTEGER NOT NULL,
  region TEXT,
  rent REAL,
  data TEXT NOT NULL CHECK(json_valid(data)),
  PRIMARY KEY (snapshot, position)
) WITHOUT ROWID;
CREATE INDEX IF NOT EXISTS listings_by_region_rent ON listings (snapshot, region, rent);

CREATE TABLE IF NOT EXISTS price_history (
  snapshot TEXT NOT NULL,
  position INTEGER NOT NULL,
  data TEXT NOT NULL CHECK(json_valid(data)),
  PRIMARY KEY (snapshot, position)
) WITHOUT ROWID;

