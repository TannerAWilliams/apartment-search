#!/usr/bin/env bun
/**
 * Rebuilds server/data/dashboard-catalog.ts from the StreetEasy dashboard archive in public/data/: every series
 * with its month range, and every area with the stable number the market history tables use for it.
 *   bun scripts/dashboard-catalog.ts
 * Run it after replacing the archive (and update DASHBOARD_ARCHIVE_PATH and its checksum in server/dashboard-snapshot.ts).
 */
import { strFromU8, unzipSync } from 'fflate';
import { parseDashboardCsv } from '../server/dashboard-csv.ts';
import { DASHBOARD_ARCHIVE_PATH } from '../server/dashboard-snapshot.ts';
import { DASHBOARD_FILES, type DashboardFile } from '../src/dashboard-data.ts';

const root = new URL('../', import.meta.url);
const archive = unzipSync(new Uint8Array(await Bun.file(new URL('public' + DASHBOARD_ARCHIVE_PATH, root)).arrayBuffer()));
const files: DashboardFile[] = DASHBOARD_FILES.filter((name) => archive[name.replace(/\.csv$/, '.zip')]).map((name) =>
  parseDashboardCsv(name, strFromU8(unzipSync(archive[name.replace(/\.csv$/, '.zip')]!)[name]!)),
);

const TYPE_ORDER = ['city', 'borough', 'neighborhood'];
const areas = new Map<string, { name: string; borough: string; type: string }>();
for (const file of files)
  for (const { name, borough, type } of file.areas) areas.set(JSON.stringify([name, borough, type]), { name, borough, type });
const sorted = [...areas.values()].sort(
  (a, b) => TYPE_ORDER.indexOf(a.type) - TYPE_ORDER.indexOf(b.type) || a.borough.localeCompare(b.borough) || a.name.localeCompare(b.name),
);
const catalog = files.map((file) => ({
  name: file.name,
  metric: file.metric,
  segment: file.segment,
  firstMonth: file.months[0],
  lastMonth: file.months.at(-1),
  areaCount: file.areas.length,
}));

const source = `// Generated by scripts/dashboard-catalog.ts from the preserved official archive. Do not edit by hand.
import type { DashboardFile } from '../../src/dashboard-data.ts';

type DashboardCatalogEntry = { name: string; metric: DashboardFile['metric']; segment: string; firstMonth: string; lastMonth: string; areaCount: number };
export const DASHBOARD_CATALOG: DashboardCatalogEntry[] = ${JSON.stringify(catalog)};

/** Every area in the archive. An area's id is its position plus one; the market history tables use it. */
export const DASHBOARD_AREAS: { name: string; borough: string; type: 'city' | 'borough' | 'neighborhood' }[] = ${JSON.stringify(sorted)};
`;
await Bun.write(new URL('server/data/dashboard-catalog.ts', root), source);
console.log(`${catalog.length} series, ${sorted.length} areas.`);
