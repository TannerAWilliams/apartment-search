import { readFile, writeFile } from 'node:fs/promises';
import { URL } from 'node:url';
import { gzipSync } from 'node:zlib';
import { parseFirstMoverCsv } from '../server/firstmover.ts';

const [csvPath, month] = process.argv.slice(2);
if (!csvPath || !/^20\d{2}-(0[1-9]|1[0-2])$/.test(month ?? '')) {
  throw new Error('Pass the CSV path and its dataset month in YYYY-MM format.');
}

const records = parseFirstMoverCsv(await readFile(csvPath, 'utf8'), month);
const encoded = gzipSync(JSON.stringify(records), { level: 9 }).toString('base64');
const target = new URL('../src/data/snapshot.ts', import.meta.url);
await writeFile(target, '// Generated by scripts/update-market.ts from FirstMover Open Data.\n' +
  '// Attribution and license accompany this file.\n' +
  `export const SNAPSHOT_MONTH = '${month}';\nexport const SNAPSHOT_GZIP = '${encoded}';\n`);
console.log(`Prepared ${records.length.toLocaleString('en-US')} eligible source rows.`);
