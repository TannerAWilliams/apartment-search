import base64 from 'base64-js';
import { parseFirstMoverCsv } from '../server/firstmover.ts';
import { decodeMarketRows, packRentMonth } from '../src/market.ts';

const files = Bun.argv.slice(2);
if (!files.length) throw new Error('Pass dated FirstMover CSV files named YYYY-MM.csv.');

const history: Record<string, ReturnType<typeof packRentMonth>> = {};
for (const file of files.sort()) {
  const month = file
    .split('/')
    .at(-1)
    ?.match(/^(20\d{2}-(?:0[1-9]|1[0-2]))\.csv$/)?.[1];
  if (!month || Object.hasOwn(history, month)) throw new Error('Each CSV needs a unique YYYY-MM filename.');
  const rows = parseFirstMoverCsv(await Bun.file(file).text(), month);
  history[month] = packRentMonth(decodeMarketRows(rows));
}
const packed = base64.fromByteArray(Bun.gzipSync(JSON.stringify(history)));
const lines = (packed.match(/.{1,100}/g) ?? []).map((line) => '  ' + JSON.stringify(line)).join(' +\n');
await Bun.write(
  new URL('../src/data/rent-history.ts', import.meta.url),
  '// Generated by scripts/update-rent-history.ts from FirstMover Open Data.\nexport const RENT_HISTORY_GZIP =\n' + lines + ';\n',
);
