#!/usr/bin/env python3
"""Build the offline snapshot from a FirstMover monthly open-data CSV."""

import argparse
import base64
import csv
import gzip
import json
from pathlib import Path
import re
from urllib.parse import urlsplit


COUNTIES = {
    "Manhattan": "New York", "Brooklyn": "Kings", "Queens": "Queens",
    "Bronx": "Bronx", "Staten Island": "Richmond",
}

NJ_ZIPS = {
    "07002": ("Bayonne", "Hudson"), "07010": ("Cliffside Park", "Bergen"),
    "07020": ("Edgewater", "Bergen"), "07024": ("Fort Lee", "Bergen"),
    "07029": ("Harrison", "Hudson"), "07030": ("Hoboken", "Hudson"),
    "07032": ("Kearny", "Hudson"), "07047": ("North Bergen", "Hudson"),
    "07086": ("Weehawken", "Hudson"), "07087": ("Union City", "Hudson"),
    "07093": ("West New York", "Hudson"), "07094": ("Secaucus", "Hudson"),
    "07302": ("Jersey City", "Hudson"), "07304": ("Jersey City", "Hudson"),
    "07305": ("Jersey City", "Hudson"), "07306": ("Jersey City", "Hudson"),
    "07307": ("Jersey City", "Hudson"), "07310": ("Jersey City", "Hudson"),
    "07311": ("Jersey City", "Hudson"),
}

EXCLUDED_BUILDING_TYPES = {"HOUSE", "TOWNHOUSE", "COMMERCIAL", "LAND"}


def nyc_borough(zip_code):
    prefix = zip_code[:3]
    if prefix in ("100", "101", "102"):
        return "Manhattan"
    if prefix == "103":
        return "Staten Island"
    if prefix == "104":
        return "Bronx"
    if prefix == "112":
        return "Brooklyn"
    if prefix in ("111", "113", "114", "116") or zip_code in ("11004", "11005"):
        return "Queens"
    return None


def record(row):
    zip_code = row["zip_code"].strip()
    street = row["street"].strip()
    neighborhood = row["neighborhood"].strip()
    state = row["state"].strip()
    source_url = urlsplit(row["url"])
    if (not street or not neighborhood or not re.fullmatch(r"\d{5}", zip_code)
            or source_url.scheme != "https" or source_url.netloc != "streeteasy.com"
            or not source_url.path.startswith(("/building/", "/rental/"))
            or row["building_type"] in EXCLUDED_BUILDING_TYPES):
        return None
    if state == "NY":
        city = nyc_borough(zip_code)
        if not city:
            return None
        county = COUNTIES[city]
    elif state == "NJ" and zip_code in NJ_ZIPS:
        city, county = NJ_ZIPS[zip_code]
        if zip_code == "07093" and neighborhood == "Guttenberg":
            city = "Guttenberg"
    else:
        return None

    try:
        bedrooms = int(row["bedrooms"])
        rent = float(row["price"])
        lat = round(float(row["latitude"]), 6)
        lon = round(float(row["longitude"]), 6)
    except ValueError:
        return None
    if not 0 <= bedrooms <= 4 or not 0 < rent <= 100_000:
        return None
    if not 40 <= lat <= 42 or not -75 <= lon <= -72:
        return None

    return [row["id"], street, row["unit"].strip(), city, county, state, zip_code,
            neighborhood, lat, lon, bedrooms, int(rent) if rent.is_integer() else rent,
            source_url.path, row["created_at_utc"][:10], row.get("source_group", "").strip()[:160]]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv_file", type=Path)
    parser.add_argument("month", help="Dataset month in YYYY-MM format")
    args = parser.parse_args()
    if not re.fullmatch(r"20\d{2}-(0[1-9]|1[0-2])", args.month):
        parser.error("Enter a month in YYYY-MM format.")

    with args.csv_file.open(encoding="utf-8-sig", newline="") as source:
        rows = list(csv.DictReader(source))
    records = []
    seen_paths = set()
    for row in sorted(rows, key=lambda item: item["created_at_utc"]):
        if row["created_at_utc"][:7] != args.month:
            parser.error("The CSV contains rows from a different month.")
        listing = record(row)
        if listing and listing[12] not in seen_paths:
            seen_paths.add(listing[12])
            records.append(listing)
    if not records:
        parser.error("The CSV contains no supported apartments.")

    raw = json.dumps(records, separators=(",", ":"), ensure_ascii=False).encode()
    encoded = base64.b64encode(gzip.compress(raw, compresslevel=9, mtime=0)).decode()
    target = Path(__file__).resolve().parents[1] / "src" / "data" / "snapshot.mjs"
    target.write_text(
        "// Generated by scripts/update-market.py from FirstMover Open Data.\n"
        "// Attribution and license accompany this file.\n"
        f"export const SNAPSHOT_MONTH = '{args.month}';\n"
        f"export const SNAPSHOT_GZIP = '{encoded}';\n",
        encoding="utf-8",
    )
    print(f"Prepared {len(records):,} eligible source rows from {len(rows):,} published observations.")


if __name__ == "__main__":
    main()
