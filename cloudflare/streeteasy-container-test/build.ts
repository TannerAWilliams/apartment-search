// Bundles probe.ts into one script and embeds it as a string the Worker passes to `bun -e`.
const result = await Bun.build({ entrypoints: [import.meta.dir + '/probe.ts'], target: 'bun', format: 'esm', minify: true });
if (!result.success || result.outputs.length !== 1) throw new Error('Probe bundle failed.');
const code = await result.outputs[0].text();
await Bun.write(import.meta.dir + '/probe.generated.ts', `// Generated by build.ts. Do not edit.\nexport default ${JSON.stringify(code)};\n`);
console.log(`Probe bundle: ${code.length} bytes`);
